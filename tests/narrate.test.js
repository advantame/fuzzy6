describe('WAV validation and safe incremental persistence', () => {
  it('accepts small PCM WAV and rejects corruption, silence, clipping, and format changes', () => {
    expect(validateWav(wav()).duration).toBe(0.2);
    expect(() => validateWav(wav(0))).toThrow('無音');
    expect(() => validateWav(wav(32767))).toThrow('飽和');
    const bad = wav(); bad.writeUInt32LE(48000, 24);
    expect(() => validateWav(bad)).toThrow('24kHz');
    expect(() => validateWav(wav().subarray(0, 100))).toThrow('RIFF');
  });
  it('dry inspection creates no output and detects orphan/tampered WAV', async () => {
    const voiceDir = await fixture();
    const state = await inspectAssets(voiceDir, [line], voice, ['1']);
    expect(state.plan[0].status).toBe('missing');
    await expect(access(join(voiceDir, 'manifest.json'))).rejects.toMatchObject({ code: 'ENOENT' });
    await writeFile(join(voiceDir, 'sample/a@1.wav'), wav());
    await expect(inspectAssets(voiceDir, [line], voice, ['1'])).rejects.toThrow('manifest にない');
    const manifest = emptyManifest(); applyRecording(manifest, update()); await save(voiceDir, manifest);
    await writeFile(join(voiceDir, 'sample/a@1.wav'), wav(200));
    await expect(inspectAssets(voiceDir, [line], voice, ['1'])).rejects.toThrow('sha256');
  });
  it('commits one take at a time and reuses it on the next run', async () => {
    const voiceDir = await fixture();
    const state = await inspectAssets(voiceDir, [line], voice, ['0.9', '1']);
    const writer = await openWriter(voiceDir, state);
    try {
      await expect(openWriter(voiceDir, state)).rejects.toThrow('ロック');
      await writer.commit(update('0.9'), wav());
    } finally { await writer.close(); }
    const next = await inspectAssets(voiceDir, [line], voice, ['0.9', '1']);
    expect(next.plan.map(p => p.status)).toEqual(['encode', 'missing']);
    expect((await readFile(join(voiceDir, 'sample/a@0.9.wav'))).equals(wav())).toBe(true);
  });
  it('detects edits after planning without overwriting them', async () => {
    const voiceDir = await fixture();
    const state = await inspectAssets(voiceDir, [line], voice, ['1']);
    const writer = await openWriter(voiceDir, state);
    try {
      await writeFile(join(voiceDir, 'sample/a@1.wav'), wav(200));
      await expect(writer.commit(update(), wav())).rejects.toThrow('変更');
      expect((await readFile(join(voiceDir, 'sample/a@1.wav'))).equals(wav(200))).toBe(true);
      await save(voiceDir, emptyManifest());
      await expect(writer.persist()).rejects.toThrow('manifestが変更');
    } finally { await writer.close(); }
  });
  it('recovers a journal after WAV rename, without writing during inspection', async () => {
    const voiceDir = await fixture();
    const manifest = emptyManifest(); manifest._pending = update();
    await save(voiceDir, manifest); await writeFile(join(voiceDir, 'sample/a@1.wav'), wav());
    const before = await readFile(join(voiceDir, 'manifest.json'));
    const state = await inspectAssets(voiceDir, [line], voice, ['1']);
    expect(state.plan[0].status).toBe('encode');
    expect(state.manifest._pending).toBeUndefined();
    expect((await readFile(join(voiceDir, 'manifest.json'))).equals(before)).toBe(true);
    const writer = await openWriter(voiceDir, state);
    try { await writer.persist(); } finally { await writer.close(); }
    expect(JSON.parse(await readFile(join(voiceDir, 'manifest.json'), 'utf8'))._pending).toBeUndefined();
  });
  it('recovers the old recording when interruption precedes WAV rename', async () => {
    const voiceDir = await fixture();
    const manifest = emptyManifest(); applyRecording(manifest, update());
    const next = update('1', { ...line, source: 'ウエ' }, wav(200));
    next.previousSha256 = sha256(wav()); manifest._pending = next;
    await save(voiceDir, manifest); await writeFile(join(voiceDir, 'sample/a@1.wav'), wav());
    const state = await inspectAssets(voiceDir, [next.line], voice, ['1']);
    expect(state.plan[0].status).toBe('stale');
    expect(state.manifest.clips.sample.a.source).toBe(line.source);
  });
  it('rejects symlinks and bounded-reader overflow using tiny inputs', async () => {
    const voiceDir = await fixture();
    const target = join(voiceDir, 'tiny.json'); await writeFile(target, '12345');
    await expect(readOptional(target, 4)).rejects.toThrow('容量');
    await symlink(target, join(voiceDir, 'sample/a@1.wav'));
    await expect(inspectAssets(voiceDir, [line], voice, ['1'])).rejects.toThrow('symlink');
  });
});

